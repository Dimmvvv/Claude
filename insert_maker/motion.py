def ease(t):  # easeInOutCubic — перемещения, маркер, приглушение
    t = min(max(t, 0.0), 1.0)
    return 4 * t ** 3 if t < 0.5 else 1 - (-2 * t + 2) ** 3 / 2


def ease_out(t):  # easeOutCubic — появления
    t = min(max(t, 0.0), 1.0)
    return 1 - (1 - t) ** 3


def ease_out_back(t, c=OVERSHOOT):  # появление с перелётом
    t = min(max(t, 0.0), 1.0)
    return 1 + (c + 1) * (t - 1) ** 3 + c * (t - 1) ** 2


def spring(t, zeta=0.7, f=2.0):
    """Пружина как чистая функция времени (секунды от старта): 0 → 1 с затухающими колебаниями."""
    if t <= 0:
        return 0.0
    w = 2 * math.pi * f
    if zeta >= 1:
        return 1 - math.exp(-w * t) * (1 + w * t)
    wd = w * math.sqrt(1 - zeta * zeta)
    return 1 - math.exp(-zeta * w * t) * (math.cos(wd * t) + (zeta * w / wd) * math.sin(wd * t))


def pop(t, dur, c=OVERSHOOT, spr=SPRING_CARD):
    """Появление «быстро вошло — плавно встало»: кривая с перелётом или пружина (по STYLE)."""
    if STYLE == "spring":
        return spring(t, *spr)
    return ease_out_back(t / dur, c)
